"""Inventory PDFs and report the status of extracted records without inflating counts."""
from collections import Counter
from pathlib import Path
import json
import re
import fitz

ROOT = Path(__file__).resolve().parent.parent
MATERIALS = ROOT / "study-materials"
BANKS = {
    "AFCAT": ROOT / "data" / "afcat-previous.json",
    "TNPSC": ROOT / "data" / "tnpsc-previous.json",
}

records = []
previous_by_exam = {"AFCAT": [], "TNPSC": []}
review_bank = []
for exam, bank_path in BANKS.items():
    bank = json.loads(bank_path.read_text(encoding="utf-8"))
    for item in bank:
        source = item.get("source", "").split(" (Page")[0]
        item["_source_filename"] = source
        match = re.search(r"20\d{2}", source)
        if match and "Solved Paper" in source or "Group-4" in source:
            item["year"] = match.group(0) if match else None
            item["questionType"] = "previous-year"
        else:
            item["questionType"] = "study-material-exercise"
        item["type"] = "previous-year" if item["questionType"] == "previous-year" else "study-material"
        page_match = re.search(r"\(Page (\d+)\)", item.get("source", ""))
        item["sourcePage"] = int(page_match.group(1)) if page_match else None
        item["language"] = "ta" if re.search(r"[\u0B80-\u0BFF]", item.get("question", "")) else "en"
        # The old extractor defaulted every answer to A; no answer is verified by that default.
        item["verification"] = "needs-review"
        records.append((exam, item))
        if item["questionType"] == "previous-year":
            previous_by_exam[exam].append(item)
        else:
            review_bank.append(item)

# Preserve review candidates created by earlier runs so the audit is repeatable.
review_path = ROOT / "data" / "question-review.json"
if review_path.exists():
    for item in json.loads(review_path.read_text(encoding="utf-8")):
        exam = "AFCAT" if item.get("exam") == "afcat" else "TNPSC"
        source = item.get("source", "").split(" (Page")[0]
        item["_source_filename"] = source
        item["questionType"] = "study-material-exercise"
        item["type"] = "study-material"
        item["verification"] = "needs-review"
        records.append((exam, item))
        review_bank.append(item)
    bank_path.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

by_source = Counter((exam, item["_source_filename"]) for exam, item in records)
for _, item in records:
    item.pop("_source_filename", None)
for exam, bank_path in BANKS.items():
    bank_path.write_text(json.dumps(previous_by_exam[exam], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
(ROOT / "data" / "question-review.json").write_text(json.dumps(review_bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
lines = [
    "STUDY MATERIAL INVENTORY AND EXTRACTION AUDIT",
    "Generated by: python scripts/audit_materials.py",
    "",
    "Status definitions: candidate = a record retained by the legacy extractor; needs-review = not safe to publish as a verified question.",
    "The legacy extractor assigned answer A by default, so verified official/independent answer counts are zero.",
    "Scanned pages require OCR. OCR is not installed in this environment; those pages are explicitly flagged.",
    "",
    "Filename | Exam | Document type | Pages | Text pages | Legacy candidate records | Verified | Needs review | Extraction status",
]
for pdf in sorted(MATERIALS.rglob("*.pdf")):
    exam = pdf.parent.name
    name = pdf.name
    doc = fitz.open(pdf)
    page_text = [page.get_text("text") for page in doc]
    text_pages = sum(bool(text.strip()) for text in page_text)
    hits = by_source[(exam, name)]
    lower = name.lower()
    if "syllabus" in lower:
        kind = "syllabus"
    elif any(token in lower for token in ("solved paper", "group-4-")):
        kind = "previous-year question paper"
    elif "answer" in lower and "key" in lower:
        kind = "answer key"
    else:
        kind = "study material"
    if text_pages == 0:
        status = "OCR required; no text layer"
    elif hits:
        status = "legacy candidates need manual text and answer review"
    elif kind == "previous-year question paper":
        status = "text available; full MCQ extraction not validated"
    else:
        status = "inventoried; not a question paper"
    lines.append(f"{name} | {exam} | {kind} | {len(doc)} | {text_pages} | {hits} | 0 | {hits} | {status}")

lines += [
    "",
    "Question bank audit",
    f"AFCAT legacy records: {sum(n for (exam, _), n in by_source.items() if exam == 'AFCAT')}; this includes study-material exercises and is not a verified previous-year count.",
    f"TNPSC legacy records: {sum(n for (exam, _), n in by_source.items() if exam == 'TNPSC')}; this includes study-material exercises and syllabus fragments.",
    "Verified official-key answers: 0. Independently verified answers: 0. Unresolved records: all legacy candidates.",
    "Question records are retained only as review candidates; the app excludes needs-review items from practice and mock tests.",
    "The 1,000-question target was not met responsibly. Existing generated placeholder banks and GK filler were removed from active delivery.",
]
(ROOT / "extraction_report.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Inventoried {len(list(MATERIALS.rglob('*.pdf')))} PDFs; report written to extraction_report.txt")
